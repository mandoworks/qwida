export type Lang = keyof typeof STRINGS;
export type StringKey = keyof (typeof STRINGS)["es"] & keyof (typeof STRINGS)["en"];
export type StringValues = { [K in StringKey]: string };

/** Replaces {name} style placeholders. Missing values are left visible on purpose. */
export function format(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in values ? String(values[key]) : whole,
  );
}

/** Looks a key up in one language. Falls back to Spanish so no string is ever blank. */
export function t(lang: Lang, key: StringKey, values?: Record<string, string | number>): string {
  const table = STRINGS[lang] as StringValues;
  const template = table[key] ?? STRINGS.es[key];
  return format(template, values);
}
